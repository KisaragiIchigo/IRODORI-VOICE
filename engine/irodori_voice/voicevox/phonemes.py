def mora_text(consonant: str | None, vowel: str) -> str:
    """子音と母音からカタカナを引く。

    無声化母音（大文字）は通常の母音と同じ表記にする。
    表にない組み合わせは、音素をそのまま返して情報を落とさない。
    """

    key = (consonant or "", vowel.lower() if vowel not in ("N", "cl") else vowel)
    text = MORA_TABLE.get(key)
    if text is not None:
        return text

    # 拗音などで子音が長い場合の保険。母音だけで引き直す。
    fallback = MORA_TABLE.get(("", key[1]))
    if fallback is not None:
        return (consonant or "") + fallback
    return (consonant or "") + vowel


def is_unvoiced(vowel: str) -> bool:
    """無声化母音かどうか。VOICEVOX はこのモーラの音高を 0 にする。"""

    return vowel in ("A", "I", "U", "E", "O")
