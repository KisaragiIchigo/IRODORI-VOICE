"""参照音声にまつわる、作り方によらない決まりごと。

参照音声の作り方は「取り込んだ話者の声を写す」（clone.py）と「シードの声を焼き付ける」
（seed_bake.py）の 2 通りある。置き場所と命名はここへ集める。
固定済みシード話者の表現優先設定は seed_profile.py が持つ。
"""

from __future__ import annotations

import uuid

from ..paths import voice_assets_dir

# 参照音声への忠実さ。上げるほど声が寄る、というものではない。
#
# 実測（ある話者を写したもの・同一文・同一シード。元の声の F0 中央値は 252Hz）:
#
#     cfg  高域(6kHz以上)の比率  F0 中央値   元の声との差
#     3.0        6.73%            246.2Hz        -5.8Hz
#     5.0        2.00%            324.3Hz       +72.3Hz
#     9.0        0.04%            310.7Hz       +58.7Hz
#
# 上げると高域が失われ、こもった音になる。9.0 では高域がほぼ消える（AM ラジオのような音）。
# F0 が下がるのも声が寄ったからではなく、単にこもった結果だった。
# 音質と声の近さがどちらも最良になる 3.0 を既定にする。
#
# なお MeanFlow 蒸留版のチェックポイントでは、この値を含む CFG スケールが
# すべて 0 に潰される。効かせるには標準版を選んでおく必要がある。
REFERENCE_SPEAKER_CFG = 3.0

# 借りた声の、喋り方の指示の効き。
#
# ノーマルはキャプションを持たないため、ここが効くのは喜怒哀楽のスタイルだけになる。
# シードの声は 5.0 で、同じ文面の指示を 1.7 倍の力で押していた。同じ顔ぶれのスタイルを
# 共有しているのに濃さが揃わないので、借りた声を 1 段上げて差を詰める。
#
# 上げ切らずに 4.0 に留めるのは、キャプションを強く押すほど声が参照から離れるため。
# ノーマルにキャプションを置かないのも同じ理由（clone.py の冒頭）。
REFERENCE_CAPTION_CFG = 4.0

# 借りた声の生成回数。
#
# 上げるほど後半のこもりが取れるが、上げるほど声が参照から離れ、生成時間も伸びる。
# 測った範囲では 8 回から上げた効果は 13 回で伸びきり、24 回・40 回との差は出なかった
# （有声区間の 6kHz 以上の振幅割合・後半のみ。ミライ 17.15% → 19.15% → 19.07% → 19.15%、
# カコ 23.12% → 23.22% → 23.45% → 23.46%、アイル 17.50% → 17.27% → 17.40% → 17.32%）。
#
# それでも 24 回を採る。利用者が 8／13／24／40 を聴き比べ、3 人とも 24 回の息遣いを
# 好ましいと判断したため。息の出方（立ち上がりの滑らかさ、有声部との繋がり、粒の細かさ）
# は上の指標では測れておらず、無声寄りの枠を取り出して量・大きさ・帯域比を見ても 13 回と
# 24 回で差が出なかった。数字が差を示さないことは、差が無いことの証明にはならない。
#
# 2026-09-18 にミライのノーマルだけ 24 回へ上げた判断とも揃う。
REFERENCE_NUM_STEPS = 24

# シードの声を焼き付けるときに読ませる文。試聴でもこれを既定に使う。
#
# 試聴で聴いた音がそのまま参照音声になるよう、両者で同じ文を共有する。シードと文が同じなら
# 出力は決定的なので、聴いたとおりの声が保存される（キャッシュには当たらない。試聴も焼き付けも
# 使い捨ての話者を作る作りで、話者 ID がキャッシュのキーに入るため）。
#
# 促音・拗音・撥音が一通り入る長さにしてある。短すぎる参照は声の手本として弱く、
# 長すぎると作成のたびに待たせることになるため、40 文字前後に収めている。
SEED_REFERENCE_TEXT = "こんにちは。今日はいい天気ですね。設定の画面から、音量や話す速さをゆっくり変えられます。"

# 声を固定したあと、同じ声で続けて読ませる文。SEED_REFERENCE_TEXT と合わせて 4 本になる。
#
# 参照が 1 本きりだと、短い区間で尺の予測が大きく外れる。実測では 9 文字の区間へ 4.72 秒が
# 割り当てられ、余った尺をモデルが言葉で埋めて同じ句を 2 度読んだ。参照を 4 本持つ借りた声は
# 同じ区間が 1.56 秒に収まる。本数を揃えて話者条件を安定させる。
#
# 1 本目を焼いたあとに合成するため、この時点で声は既に固定されている。焼く前に 4 本を
# 別々に合成すると 4 人ぶんの声が混ざるが（seed_bake.py の冒頭）、この順序なら起きない。
SEED_FOLLOWUP_TEXTS: tuple[str, ...] = (
    "新しい機能の説明をします。画面の右上から、書き出し先を選んでください。",
    "ありがとうございました。またのご利用を、心よりお待ちしております。",
    "特急列車が到着します。黄色い線の内側まで、お下がりください。",
)

# Irodori-TTS が参照として受け取れる長さの上限。超えた分は捨てられるため、合成の段階で
# 打ち切る。借りた声も同じ上限を clone.py に持つが、あちらは完成しているため触らない。
SEED_REFERENCE_MAX_SECONDS = 30.0

# 焼き付けた参照音声の先頭へ入れる無音の長さ。
#
# モデルが参照なしで合成した音は、無音の助走をほとんど持たない（実測 13〜24ms）。借りた声の
# 参照は Style-Bert-VITS2 の出力で 104〜144ms ある。助走の短い参照を手本にすると、生成音声が
# 0 サンプル目から大振幅で始まり（実測の 1 サンプル目が -11272）、再生した瞬間に破裂音が出る。
# 短い本文では読み上げる長さの予測も外れ、余った尺が冒頭の音や本文に無い語になる。
#
# 先頭へ 130ms 足した参照で鳴らすと、生成音声の助走が 198〜221ms へ戻り、1 サンプル目が
# ほぼ 0 になった。7 モーラの尺も 2.32 秒から 1.72〜1.80 秒へ縮み、借りた声の 1.56 秒に近づく。
# 参照 1 本あたり 130ms で、上限 30 秒に対しては無視できる。
SEED_REFERENCE_LEAD_SECONDS = 0.13


def save_reference_wavs(wavs: list[bytes]) -> list[str]:
    """参照音声をアセット領域へ書き出し、保存したファイル名を返す。"""

    root = voice_assets_dir()
    names: list[str] = []
    for wav in wavs:
        name = f"ref-{uuid.uuid4().hex[:12]}.wav"
        (root / name).write_bytes(wav)
        names.append(name)
    return names


def remove_reference_wavs(names: list[str]) -> None:
    """書き出した参照音声を消す。何本かに分けて焼く途中で失敗したときの後始末に使う。"""

    root = voice_assets_dir()
    for name in names:
        (root / name).unlink(missing_ok=True)
