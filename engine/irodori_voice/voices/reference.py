"""参照音声にまつわる、作り方によらない決まりごと。

参照音声の作り方は「取り込んだ話者の声を写す」（clone.py）と「シードの声を焼き付ける」
（seed_bake.py）の 2 通りある。置き場所と命名はここへ集める。
固定済みシード話者の表現優先設定は seed_profile.py が持つ。
"""

from __future__ import annotations

import uuid

from ..paths import voice_assets_dir

# 参照音声への忠実さ。上げるほど声が寄る、というものではない。
#
# 実測（ある話者を写したもの・同一文・同一シード。元の声の F0 中央値は 252Hz）:
#
#     cfg  高域(6kHz以上)の比率  F0 中央値   元の声との差
#     3.0        6.73%            246.2Hz        -5.8Hz
#     5.0        2.00%            324.3Hz       +72.3Hz
#     9.0        0.04%            310.7Hz       +58.7Hz
#
# 上げると高域が失われ、こもった音になる。9.0 では高域がほぼ消える（AM ラジオのような音）。
# F0 が下がるのも声が寄ったからではなく、単にこもった結果だった。
# 音質と声の近さがどちらも最良になる 3.0 を既定にする。
#
# なお MeanFlow 蒸留版のチェックポイントでは、この値を含む CFG スケールが
# すべて 0 に潰される。効かせるには標準版を選んでおく必要がある。
REFERENCE_SPEAKER_CFG = 3.0

# シードの声を焼き付けるときに読ませる文。試聴でもこれを既定に使う。
#
# 試聴で聴いた音がそのまま参照音声になるよう、両者で同じ文を共有する。シードと文が同じなら
# 出力は決定的なので、聴いたとおりの声が保存される（キャッシュには当たらない。試聴も焼き付けも
# 使い捨ての話者を作る作りで、話者 ID がキャッシュのキーに入るため）。
#
# 促音・拗音・撥音が一通り入る長さにしてある。短すぎる参照は声の手本として弱く、
# 長すぎると作成のたびに待たせることになるため、40 文字前後に収めている。
SEED_REFERENCE_TEXT = "こんにちは。今日はいい天気ですね。設定の画面から、音量や話す速さをゆっくり変えられます。"


def save_reference_wavs(wavs: list[bytes]) -> list[str]:
    """参照音声をアセット領域へ書き出し、保存したファイル名を返す。"""

    root = voice_assets_dir()
    names: list[str] = []
    for wav in wavs:
        name = f"ref-{uuid.uuid4().hex[:12]}.wav"
        (root / name).write_bytes(wav)
        names.append(name)
    return names
