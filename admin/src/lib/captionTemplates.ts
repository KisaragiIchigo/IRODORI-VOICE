/**
 * 表現の指示（caption）のテンプレ。
 *
 * モデルは自由文をそのまま条件として受け取るため、決まった語彙は存在しない。ここに並べるのは
 * 同梱プリセットと喜怒哀楽スタイルで実際に使っている言い回しを土台に、同じ話者・同じ文・
 * 同じシードで「指示なし」と比べ、音が動くことを実測で確かめたものだけ。
 *
 * 選べるのはこの一覧だけで、自由入力の欄は置いていない。モデルが受け取れる語彙は開いている
 * が、効くかどうかは実測しないと分からず、効かない指示を書ける欄があると「指定したのに何も
 * 変わらない」という結果だけが残るため。
 *
 * 「ごく近い距離でささやくように話している。」は、参照音声を持つ話者では音がまったく動かな
 * かったため外している（時間を揃えた MFCC 距離が他の 17〜22 に対して 7.7、長さも完全に同一）。
 * ささやき声は喜怒哀楽スタイル側にあるので、そちらを使う。
 *
 * 「関西なまりで話している。」も外した。方言の実体はアクセント核の位置と語彙だが、モデルは
 * 音素列ではなく書かれたテキストをそのまま受け取るため、キャプション側からアクセントへは
 * 手が届かない。参照音声を持つ話者では抑揚の骨格を参照側が決めるので、なおさら動かない。
 * 方言で読ませる場合は、読み上げ文そのものを方言で書く。
 */

export type CaptionTemplate = {
  /** 選択肢に出す短い名前。 */
  label: string;
  /** モデルへ渡す文章そのもの。 */
  caption: string;
};

